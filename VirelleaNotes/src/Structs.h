//----------------------------------------------------------------------------
//! @file   Structs.h
//! @brief  基本構造体の定義
//! @detail 2D位置、サイズ、画像プロパティ、ノーツデータなどプロジェクトで共通利用する軽量なデータ構造を定義します。
//----------------------------------------------------------------------------
#pragma once
#include <string>
#include <memory>

//-----------------------------------------------------------
//! @brief 2D位置（float）
//-----------------------------------------------------------
struct FloatPos
{
    float x = 0.0f;    //!< X位置
    float y = 0.0f;    //!< Y位置
};

//-----------------------------------------------------------
//! @brief 2D位置（int）
//-----------------------------------------------------------
struct IntPos
{
    int x = 0;    //!< X位置
    int y = 0;    //!< Y位置
};

//-----------------------------------------------------------
//! @brief 2D線位置（float）
//-----------------------------------------------------------
struct FloatLinePos
{
    FloatPos pos_1 = {0.0f, 0.0f};    //!< 位置1
    FloatPos pos_2 = {0.0f, 0.0f};    //!< 位置2
};

//-----------------------------------------------------------
//! @brief 2D線位置（int）
//-----------------------------------------------------------
struct IntLinePos
{
    IntPos pos_1 = {0, 0};    //!< 位置1
    IntPos pos_2 = {0, 0};    //!< 位置2
};

//-----------------------------------------------------------
//! @brief サイズ（float）
//-----------------------------------------------------------
struct FloatSize
{
    float w = 0.0f;    //!< 幅
    float h = 0.0f;    //!< 高さ
};

//-----------------------------------------------------------
//! @brief サイズ（int）
//-----------------------------------------------------------
struct IntSize
{
    int w = 0;    //!< 幅
    int h = 0;    //!< 高さ
};

//-----------------------------------------------------------
//! @brief 画像入力情報（float）
//-----------------------------------------------------------
struct ImageInputF
{
    int   image = 0;       //!< 画像ハンドル
    float w     = 0.0f;    //!< 幅
    float h     = 0.0f;    //!< 高さ
    float rot   = 0.0f;    //!< 回転角（ラジアン）
};

//-----------------------------------------------------------
//! @brief 画像入力情報（int）
//-----------------------------------------------------------
struct ImageInputI
{
    int   image = 0;       //!< 画像ハンドル
    int   w     = 0;       //!< 幅
    int   h     = 0;       //!< 高さ
    float rot   = 0.0f;    //!< 回転角（ラジアン）
};

//-----------------------------------------------------------
//! @brief 画像プロパティ（float）
//-----------------------------------------------------------
struct ImagePropertyF
{
    FloatPos pos;             //!< 位置
    int      image = 0;       //!< 画像ハンドル
    int      w     = 0;       //!< 幅
    int      h     = 0;       //!< 高さ
    float    rot   = 0.0f;    //!< 回転角（ラジアン）
};

//-----------------------------------------------------------
//! @brief ボックス（float）
//-----------------------------------------------------------
struct BoxF
{
    float x = 0.0f;    //!< 左上X
    float y = 0.0f;    //!< 左上Y
    float w = 0.0f;    //!< 幅
    float h = 0.0f;    //!< 高さ
};

//-----------------------------------------------------------
//! @brief ボックス（int）
//-----------------------------------------------------------
struct BoxI
{
    int x = 0;    //!< 左上X
    int y = 0;    //!< 左上Y
    int w = 0;    //!< 幅
    int h = 0;    //!< 高さ
};

//-----------------------------------------------------------
//! @brief カラー
//-----------------------------------------------------------
struct RGB
{
    int r = 0;    //!< 赤
    int g = 0;    //!< 緑
    int b = 0;    //!< 青
};

//-----------------------------------------------------------
//! @struct LineJudgeResult
//! @brief  ライン毎の判定結果を保持する構造体
//-----------------------------------------------------------
struct LineJudgeResult
{
    int missCount{};       //!< MISS回数
    int badCount{};        //!< BAD回数
    int goodCount{};       //!< GOOD回数
    int perfectCount{};    //!< PERFECT回数
    int totalScore{};      //!< 合計スコア
};

//--------------------------------------------------------
//! @struct NoteData
//! @brief  ノーツ1つ分のデータ
//--------------------------------------------------------
struct NoteData
{
    int  time_ms = 0;        //!< 時刻（ミリ秒）
    int  line    = 0;        //!< レーン番号
    int  type    = 0;        //!< ノーツ種類 (NOTE_TYPE)
    bool spawned = false;    //!< 生成済みフラグ
};

//--------------------------------------------------------
//! @struct DataSet
//! @brief  CSV と音源のペア情報
//--------------------------------------------------------
struct DataSet
{
    std::string csv_path;      //!< CSV ファイルパス
    std::string music_path;    //!< 音源ファイルパス
};

// 前方宣言
class NotesObject;

//--------------------------------------------------------
//! @struct HoldNotePair
//! @brief ホールドノーツの開始/終了ペア情報
//--------------------------------------------------------
struct HoldNotePair
{
    std::shared_ptr<NotesObject> start;                               //!< 開始ノーツ
    std::shared_ptr<NotesObject> end;                                 //!< 終了ノーツ
    bool                         isHolding         = false;           //!< 押している状態
    bool                         isFailed          = false;           //!< 失敗フラグ
    bool                         isSuccess         = false;           //!< 成功フラグ
    bool                         isDraw            = true;            //!< 描画有無
    FloatPos                     startPos          = {0.0f, 0.0f};    //!< 開始位置
    bool                         isStartFixed      = false;           //!< 開始位置固定フラグ
    int                          hold_effect_timer = 0;               //!< エフェクトタイマー
};

//--------------------------------------------------------
//! @struct Particle
//! 判断エフェクト用パーティクルデータを保持する構造体
//--------------------------------------------------------
struct Particle
{
    float x        = 0.0f;    //!< 位置X
    float y        = 0.0f;    //!< 位置Y
    float vx       = 0.0f;    //!< X方向速度
    float vy       = 0.0f;    //!< Y方向速度
    float size     = 0.0f;    //!< サイズ
    int   life     = 0;       //!< 生存時間
    int   max_life = 0;       //!< 最大生存時間
    int   alpha    = 0;       //!< 透明度(0-255)
};
