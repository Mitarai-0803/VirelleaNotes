#pragma once
#include "ObjectBase.h"
#include "Structs.h"

namespace Object {
//-----------------------------------------------------------
//! @class NotesObject
//! @brief ノーツのオブジェクトクラス
//-----------------------------------------------------------
class NotesObject : public ObjectBase
{
public:
    //-----------------------------------------------------------
    //! @brief 初期化処理
    //-----------------------------------------------------------
    void OnInit() override;

    //-----------------------------------------------------------
    //! @brief 更新処理
    //-----------------------------------------------------------
    void OnUpdate() override;

    //-----------------------------------------------------------
    //! @brief 描画処理
    //-----------------------------------------------------------
    void OnDraw() override;

    //-----------------------------------------------------------
    //! @brief 終了処理
    //-----------------------------------------------------------
    void OnEnd() override;

    //-----------------------------------------------------------
    //! @brief 座標を設定
    //-----------------------------------------------------------
    void SetPos(float x, float y);

    //-----------------------------------------------------------
    //! @brief ノーツタイプを設定
    //-----------------------------------------------------------
    void SetNotesType(int type);

    //-----------------------------------------------------------
    //! @brief 座標を取得
    //-----------------------------------------------------------
    FloatPos GetPos();

    //-----------------------------------------------------------
    //! @brief ノーツタイプを取得
    //-----------------------------------------------------------
    int GetNotesType();

    //-----------------------------------------------------------
    //! @brief ノーツ画像を設定
    //-----------------------------------------------------------
    void SetNotesImage(int& notes_image_handle);

private:
    FloatPos m_pos          = {0.0f};    //!< ノーツの位置
    float    m_speed        = 0.0f;      //!< ノーツの速度
    int      m_notes_type   = 0;         //!< ノーツのタイプ
    int      m_assigned_key = -1;        //!< このノーツに対応するキー
    int      m_image_handle = -1;        //!< ノーツ画像
};
}    // namespace Object
