//----------------------------------------------------------------------------
#pragma once    // インクルードガード

#include <string>
#include <vector>
#include "Font.h"
#include "LineObject.h"
#include "ObjectBase.h"
#include "ResourceHandles.h"
#include "Structs.h"

//============================================================================
//! @class  CSVLoadObject
//! @details CSV 読み込みと音源ハンドル管理を行うオブジェクトの宣言
//============================================================================
namespace Object {

class CSVLoadObject : public ObjectBase
{
public:
    //--------------------------------------------------------
    //! @brief 初期化処理
    //--------------------------------------------------------
    void OnInit();

    //--------------------------------------------------------
    //! @brief 描画処理
    //--------------------------------------------------------
    void OnDraw();

    //--------------------------------------------------------
    //! @brief 終了処理
    //--------------------------------------------------------
    void OnEnd();

    //--------------------------------------------------------
    //! @brief 利用可能データセットの再走査
    //! @param  [in] root_path  走査するルートパス
    //--------------------------------------------------------
    static void RefreshAvailableDataSets(const std::string& root_path = "data");

    //--------------------------------------------------------
    //! @brief CSV 読み込み
    //! @param  [in] file_path  読み込む CSV ファイルパス
    //! @return 読み込み成功で true
    //--------------------------------------------------------
    bool LoadCsv(const std::string& file_path);

    //--------------------------------------------------------
    //! @brief ノーツデータ取得
    //! @return ノーツデータ配列への参照
    //--------------------------------------------------------
    const std::vector<NoteData>& GetNotesData() const;

    //--------------------------------------------------------
    //! @brief 譜面切り替え
    //! @param  [in] index  切り替えるインデックス
    //--------------------------------------------------------
    void SetIndex(int index);

    //--------------------------------------------------------
    //! @brief 読み込まれた音源ハンドル取得
    //! @return 音源ハンドル
    //--------------------------------------------------------
    int GetHandle();

    //--------------------------------------------------------
    //! @brief 解析用音源ハンドル取得
    //! @return 解析用音源ハンドル
    //--------------------------------------------------------
    int GetSoftHandle();

    //--------------------------------------------------------
    //! @brief グローバル選択インデックス設定
    //! @param  [in] idx  設定するインデックス
    //--------------------------------------------------------
    static void SetSelectedIndex(int idx);

    //--------------------------------------------------------
    //! @brief グローバル選択インデックス取得
    //! @return 現在の選択インデックス
    //--------------------------------------------------------
    static int GetSelectedIndex();

    //--------------------------------------------------------
    //! @brief 利用可能データセット一覧取得
    //! @return データセット配列への参照
    //--------------------------------------------------------
    static const std::vector<DataSet>& GetAvailableDataSets();

private:
    //--------------------------------------------------------
    //! @brief data フォルダ走査
    //! @param  [in] root_path  走査ルート
    //--------------------------------------------------------
    void ScanDataDirectory(const std::string& root_path);

    inline std::string NormalizePath(const std::string& path)
    {
        std::string out = path;
        for(auto& c : out) {
            if(c == '\\')
                c = '/';
        }
        return out;
    }

    std::vector<NoteData> m_notes;                //!< ノーツ配列
    SoundHandle           m_sound_handle;         //!< 再生ハンドル（RAII）
    SoftSoundHandle       m_soft_handle;          //!< 解析ハンドル（RAII）
    int                   m_current_index = 0;    //!< 現在インデックス
};

}    // namespace Object
