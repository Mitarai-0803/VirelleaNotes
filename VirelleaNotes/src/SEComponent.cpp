//! @file   SEComponent.cpp
//! @brief  SE 再生用コンポーネントの実装
//! @detail ショートサウンド（効果音）を読み込み再生するためのコンポーネントです。
//----------------------------------------------------------------------------
#include "SEComponent.h"
#include <DxLib.h>

namespace Audio {
//--------------------------------------------------------
//! 初期化処理
//--------------------------------------------------------
void SEComponent::Init()
{
    // 特に初期化処理なし
}

//--------------------------------------------------------
//! 更新処理
//--------------------------------------------------------
void SEComponent::Update()
{
    // 効果音は即時再生で管理するため更新処理なし
}

//--------------------------------------------------------
//! 終了処理
//--------------------------------------------------------
void SEComponent::End()
{
    // SoundHandle のデストラクタで解放される
}

//--------------------------------------------------------
//! パス設定とロード
//--------------------------------------------------------
void SEComponent::SetPath(const std::string& path)
{
    m_sound_handle = SoundHandle::Load(path);
}

//--------------------------------------------------------
//! 再生
//--------------------------------------------------------
void SEComponent::Play()
{
    if(!m_sound_handle.IsValid())
        return;
    PlaySoundMem(m_sound_handle.Get(), DX_PLAYTYPE_BACK, FALSE);
}
}    // namespace Audio
