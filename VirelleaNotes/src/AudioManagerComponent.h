//----------------------------------------------------------------------------
//! @file   AudioManagerComponent.h
//! @brief  音源管理コンポーネントの宣言
//! @detail 音源の再生・停止、音量制御、再生位置の管理などの機能を提供するコンポーネントの宣言です。
//!         内部で DxLib のサウンド API を利用してハンドル管理を行います。
//----------------------------------------------------------------------------
#pragma once

#include "ComponentBase.h"    //!< コンポーネント基底クラス

//============================================================================
//! @class  AudioManagerComponent
//! 音源再生管理を行うコンポーネントの具体実装の宣言。
//============================================================================
namespace Audio {
class AudioManagerComponent : public ComponentBase
{
public:
    //--------------------------------------------------------
    //! コンストラクタ
    //--------------------------------------------------------
    AudioManagerComponent();

    //--------------------------------------------------------
    //! 初期化処理
    //! @detail 内部状態とハンドルを初期化する。
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    //! 更新処理
    //! @detail サウンド関連の定期更新を行う。
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    //! 終了処理
    //! @detail 保持するハンドルを解放する。
    //--------------------------------------------------------
    void End();

    //--------------------------------------------------------
    //! 再生開始処理
    //--------------------------------------------------------
    void HandlePlaySound();

    //--------------------------------------------------------
    //! 停止処理
    //--------------------------------------------------------
    void HandleStopSound();

    //--------------------------------------------------------
    //! 音源ハンドル設定
    //! @param  [in] handle  設定する音源ハンドル
    //--------------------------------------------------------
    void SetHandle(int handle);

    //--------------------------------------------------------
    //! 音量設定
    //! @param  [in] volume  設定する音量(0-255)
    //--------------------------------------------------------
    void SetSoundVolume(int volume);

    //--------------------------------------------------------
    //! 停止位置取得
    //! @return ミリ秒単位の停止位置
    //--------------------------------------------------------
    int GetStopPosition() const;

    //--------------------------------------------------------
    //! 再生位置取得（サンプル単位）
    //! @return サンプル単位の再生位置
    //--------------------------------------------------------
    int GetSampleTime() const;

    //--------------------------------------------------------
    //! 再生位置取得（ミリ秒単位）
    //! @return ミリ秒単位の再生位置
    //--------------------------------------------------------
    int GetMsTime() const;

    //--------------------------------------------------------
    //! 再生状態取得
    //! @return 再生中なら true
    //--------------------------------------------------------
    bool GetPlayeMode() const;

private:
    int  m_load_handle     = 0;        //!< 音声ハンドル（DxLib）
    int  m_stop_position   = 0;        //!< 停止位置（ミリ秒）
    int  m_prev_volume     = 0;        //!< 前フレームの音量
    int  m_current_volume  = 0;        //!< 現在の音量
    int  m_sample_time_pos = 0;        //!< 再生位置（サンプル）
    int  m_ms_time_pos     = 0;        //!< 再生位置（ミリ秒）
    bool m_play_mode       = false;    //!< 再生中フラグ
};
}    // namespace Audio
