//----------------------------------------------------------------------------
//! @file   PauseObject.h
//! @brief  ポーズ画面を描画する ObjectBase
//! @detail シーンのポーズ状態に応じてポーズ用オーバーレイを描画します。
//----------------------------------------------------------------------------
#pragma once

#include "ObjectBase.h"
#include "ConstantsRhythm.h"

namespace Object {
//----------------------------------------------------------------------------
//! @class PauseObject
//! @brief ポーズ画面表示用の簡易オブジェクト
//----------------------------------------------------------------------------
class PauseObject : public ObjectBase
{
public:
    //--------------------------------------------------------
    //! @brief コンストラクタ
    //--------------------------------------------------------
    PauseObject() = default;
    //--------------------------------------------------------
    //! @brief デストラクタ
    //--------------------------------------------------------
    ~PauseObject() override = default;

private:
    //--------------------------------------------------------
    //! @brief 初期化処理
    //--------------------------------------------------------
    void OnInit() override;
    //--------------------------------------------------------
    //! @brief 描画処理
    //--------------------------------------------------------
    void OnDraw() override;

    // ボックスサイズ（定数を初期値として保持）
    int m_box_w = PAUSE_BOX_W;    //!< ポーズ表示用ボックスの幅
    int m_box_h = PAUSE_BOX_H;    //!< ポーズ表示用ボックスの高さ
    // ボックス描画位置（左上座標）
    int m_box_x = 0;    //!< ボックス左上 X（OnInit で計算）
    int m_box_y = 0;    //!< ボックス左上 Y（OnInit で計算）

    // フォントハンドルのキャッシュ
    int m_big_font   = 0;    //!< 大きいフォント（PAUSE テキスト用）のハンドル
    int m_small_font = 0;    //!< 小さいフォント（サブテキスト／操作案内用）のハンドル

    // PAUSE テキストの描画レイアウト（幅・高さ・表示位置）
    int m_text_w = 0;    //!< PAUSE 文字列の幅
    int m_text_h = 0;    //!< PAUSE 文字列の高さ
    int m_text_x = 0;    //!< PAUSE 文字列描画 X
    int m_text_y = 0;    //!< PAUSE 文字列描画 Y

    // サブテキストの描画レイアウト（幅・高さ・表示位置）
    int m_sub_w = 0;    //!< サブテキストの幅
    int m_sub_h = 0;    //!< サブテキストの高さ
    int m_sub_x = 0;    //!< サブテキスト描画 X
    int m_sub_y = 0;    //!< サブテキスト描画 Y

    // 操作案内（情報）文字列の描画レイアウト
    int  m_info_w1 = 0;        //!< 1 行目（タイトル戻る案内）の幅
    int  m_info_w2 = 0;        //!< 2 行目（曲選択戻る案内）の幅
    int  m_info_x1 = 0;        //!< 1 行目の描画 X
    int  m_info_x2 = 0;        //!< 2 行目の描画 X
    int  m_info_y1 = 0;        //!< 1 行目の描画 Y
    int  m_info_y2 = 0;        //!< 2 行目の描画 Y
    bool m_pause_visible = false;    //!< シーンがポーズ中かどうかのキャッシュ（現状は OnInit で初期化するのみ。描画判定は GameScene::IsPaused() を使用）
};
}    // namespace Object
