//----------------------------------------------------------------------------
//! @file   ImageHandle.h
//! @brief  画像ハンドル管理クラスの宣言
//! @detail DxLib の画像ハンドルを RAII で扱う `ImageHandle` クラスの宣言を提供します。
//----------------------------------------------------------------------------
#pragma once

#include <string>
#include <DxLib.h>

//============================================================================
//! @class ImageHandle
//! @brief 画像ハンドルを所有・管理する小さな RAII ラッパー
//! @detail DxLib の画像ハンドルを所有し、スコープを抜けると自動的に解放します。
//============================================================================
class ImageHandle
{
public:
    //----------------------------------------------------------------------------
    //! デフォルトコンストラクタ
    //! @note 無効なハンドルを示す -1 で初期化する
    //----------------------------------------------------------------------------
    ImageHandle() noexcept;

    //----------------------------------------------------------------------------
    //! ハンドル指定コンストラクタ
    //! @param h DxLib の画像ハンドル
    //----------------------------------------------------------------------------
    explicit ImageHandle(int h) noexcept;

    //----------------------------------------------------------------------------
    //! 画像ファイルからハンドルをロードして ImageHandle を返す
    //! @param path 画像ファイルのパス
    //! @return 読み込まれたハンドルを保持する ImageHandle
    //----------------------------------------------------------------------------
    static ImageHandle Load(const std::string& path);

    //----------------------------------------------------------------------------
    //! デストラクタ
    //! @note 有効なハンドルがあれば解放する
    //----------------------------------------------------------------------------
    ~ImageHandle();

    ImageHandle(const ImageHandle&)            = delete;    //!< コピー禁止
    ImageHandle& operator=(const ImageHandle&) = delete;    //!< コピー禁止

    //----------------------------------------------------------------------------
    //! ムーブコンストラクタ
    //! @param o 移動元オブジェクト
    //----------------------------------------------------------------------------
    ImageHandle(ImageHandle&& o) noexcept;

    //----------------------------------------------------------------------------
    //! ムーブ代入演算子
    //! @param o 移動元オブジェクト
    //! @return *this
    //----------------------------------------------------------------------------
    ImageHandle& operator=(ImageHandle&& o) noexcept;

    //----------------------------------------------------------------------------
    //! ハンドルが有効かを返す
    //! @return 有効なら true
    //----------------------------------------------------------------------------
    bool IsValid() const noexcept;

    //----------------------------------------------------------------------------
    //! 内部の生ハンドルを取得する
    //! @return DxLib の画像ハンドル
    //----------------------------------------------------------------------------
    int Get() const noexcept;

    //----------------------------------------------------------------------------
    //! 真偽評価
    //! @return ハンドルが有効なら true
    //----------------------------------------------------------------------------
    explicit operator bool() const noexcept;

    //----------------------------------------------------------------------------
    //! ハンドルを解放して値を返す
    //! @return 解放前のハンドル値
    //----------------------------------------------------------------------------
    int Release() noexcept;

    //----------------------------------------------------------------------------
    //! ハンドルを交換する
    //! @param o 交換先オブジェクト
    //----------------------------------------------------------------------------
    void swap(ImageHandle& o) noexcept;

private:
    int m_h = -1;    //!< 所有している DxLib の画像ハンドル（-1 は無効）
};
