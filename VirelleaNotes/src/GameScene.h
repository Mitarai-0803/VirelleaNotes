#pragma once
#include "SceneBase.h"

namespace Scene {
//-----------------------------------------------------------
//! @class GameScene
//! @brief ゲーム本編を管理するシーンクラス
//! @details　各種 UI コンポーネントや音楽関連コンポーネントを登録する
// Scene のライフサイクル（初期化、更新、描画、終了）を制御
//-----------------------------------------------------------
class GameScene : public SceneBase
{
public:
    //-------------------------------------------------------
    //! @brief 選択された曲のインデックスを設定
    //! @param  [in] index 選択された曲のインデックス
    //-------------------------------------------------------
    void SetSelectedSongIndex(int index);

    //-------------------------------------------------------
    //! @brief 設定されている選択インデックスを取得
    //-------------------------------------------------------
    int GetSelectedSongIndex() const;

    //-------------------------------------------------------
    //! @brief ポーズ状態の取得
    //! @return ポーズ中なら true
    //-------------------------------------------------------
    static bool IsPaused();
    //-------------------------------------------------------
    //! @brief カウントダウン中かどうかの取得
    //! @return カウントダウン中なら true
    //-------------------------------------------------------
    static bool IsCountingDown();

private:
    //-------------------------------------------------------
    //! @brief シーン初期化処理
    //! @details コンポーネントを `ObjectBase` に登録し、シーンに追加する。
    //-------------------------------------------------------
    void SceneInit() override;

    //-------------------------------------------------------
    //! @brief シーン更新処理
    //! @details 登録された `ObjectBase` およびコンポーネントを毎フレーム更新する。
    //-------------------------------------------------------
    void SceneUpdate() override;

    //-------------------------------------------------------
    //! @brief シーン描画処理
    //! @details 登録された `ObjectBase` およびコンポーネントを描画する。
    //-------------------------------------------------------
    void SceneDraw() override;

    //-------------------------------------------------------
    //! @brief シーン終了処理
    //! @details 登録された `ObjectBase` やコンポーネントの終了処理を呼び出す。
    //-------------------------------------------------------
    void SceneEnd() override;

    // 描画/更新で頻繁に使われるハンドル等はメンバとしてキャッシュする
    int m_font50 = 0;    // 大きいフォント ハンドル (50px 相当)
    int m_font40 = 0;    // 中くらいのフォント ハンドル (40px 相当)
    int m_font25 = 0;    // 小さいフォント ハンドル (25px 相当)
};

}    // namespace Scene
