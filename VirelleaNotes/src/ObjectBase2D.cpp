#include "ObjectBase2D.h"

namespace Object{
//-----------------------------------------------------------
//! @brief X座標を取得する
//! @return スクリーンX座標
//-----------------------------------------------------------
float ObjectBase2D::GetX() const
{
    return m_x;
}

//-----------------------------------------------------------
//! @brief Y座標を取得する
//! @return スクリーンY座標
//-----------------------------------------------------------
float ObjectBase2D::GetY() const
{
    return m_y;
}

//-----------------------------------------------------------
//! @brief X座標を設定する
//! @param x 設定するX座標
//-----------------------------------------------------------
void ObjectBase2D::SetX(float x)
{
    m_x = x;
}

//-----------------------------------------------------------
//! @brief Y座標を設定する
//! @param y 設定するY座標
//-----------------------------------------------------------
void ObjectBase2D::SetY(float y)
{
    m_y = y;
}

//-----------------------------------------------------------
//! @brief X・Y座標をまとめて設定する
//! @param x 設定するX座標
//! @param y 設定するY座標
//-----------------------------------------------------------
void ObjectBase2D::SetPos(float x, float y)
{
    m_x = x;
    m_y = y;
}

}    // namespace Object
