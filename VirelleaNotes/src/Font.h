#pragma once
//============================================================================
//! @file   Font.h
//! @brief  フォント管理ユーティリティの宣言
//! @author レオ
//============================================================================
namespace Font
{
    //! @brief フォントインデックス
    enum FontIndex
    {
        FONT_SIZE_60_INDEX = 0,    //!< フォントサイズ 70 のインデックス
        FONT_SIZE_50_INDEX,        //!< フォントサイズ 50 のインデックス
        FONT_SIZE_40_INDEX,        //!< フォントサイズ 40 のインデックス
        FONT_SIZE_30_INDEX,        //!< フォントサイズ 30 のインデックス
        FONT_SIZE_20_INDEX,        //!< フォントサイズ 25 のインデックス
        FONT_SIZE_10_INDEX,        //!< フォントサイズ 10 のインデックス
        FONT_MAX                   //!< フォントの最大数
    };

    void FontInit();
    void FontExit();

    //-----------------------------------------------------------
    //! @param font_index フォントインデックス
    //! @return フォントハンドル
    //-----------------------------------------------------------
    int GetFont(int font_index);

    //-----------------------------------------------------------
    //! @class FontManager
    //! @brief フォントを管理するクラス
    //! @details フォントハンドル配列をプライベートメンバとして保持し、
    //!          初期化・解放・取得処理を提供する
    //-----------------------------------------------------------
    class FontManager
    {
    public:
        static void Init();
        static void Exit();

        //-----------------------------------------------------------
        //! @param font_index フォントインデックス
        //! @return フォントハンドル
        //-----------------------------------------------------------
        static int GetFont(int font_index);

    private:
        static int m_font_handles[FONT_MAX];    //!< フォントハンドル配列
    };

}    // namespace Font
