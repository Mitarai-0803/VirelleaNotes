#pragma once

#include <DxLib.h>
#include <vector>
#include "Structs.h"

//----------------------------------------------------------------------------
//! @file   JudgeEffect.h
//! @brief  判定エフェクト用クラス
//! @detail DrawFillBox を用いた単純なエフェクトを提供します。
//----------------------------------------------------------------------------

namespace Object {
//-----------------------------------------------------------
//! 判定エフェクト管理クラス
//! @detail 位置・サイズ・パーティクルの管理を行うクラスです
//-----------------------------------------------------------
class JudgeEffect
{
public:
    //----------------------------------------------------------------------------
    // コンストラクタ
    //----------------------------------------------------------------------------
    JudgeEffect();

    //----------------------------------------------------------------------------
    // エフェクト開始
    //! @param [in] x       エフェクト位置X
    //! @param [in] y       エフェクト位置Y
    //! @param [in] color   色 (GetColorで指定)
    //! @param [in] duration 継続時間
    //! @param [in] count   パーティクル数（省略時 10）
    //----------------------------------------------------------------------------
    void Start(float x, float y, unsigned int color, int duration, int count = 10);

    //----------------------------------------------------------------------------
    // 初期化
    //----------------------------------------------------------------------------
    void OnInit();

    //----------------------------------------------------------------------------
    // 更新
    //----------------------------------------------------------------------------
    void OnUpdate();

    //----------------------------------------------------------------------------
    // 描画
    //----------------------------------------------------------------------------
    void OnDraw() const;

    //----------------------------------------------------------------------------
    // 生存判定
    //----------------------------------------------------------------------------
    bool IsAlive() const;

private:
    float        m_x;           //!< 位置X
    float        m_y;           //!< 位置Y
    float        m_size;        //!< エフェクトサイズ
    float        m_max_size;    //!< 最大サイズ
    int          m_duration;    //!< 継続時間
    int          m_elapsed;     //!< 経過時間
    unsigned int m_color;       //!< 色
    bool         m_alive;       //!< 生存フラグ

    std::vector<Particle> m_particles;    //!< パーティクル配列
};
}    // namespace Object
