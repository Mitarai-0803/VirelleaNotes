//----------------------------------------------------------------------------
//! @file   ImageHandle.cpp
//! @brief  画像ハンドルの実装
//! @detail `ImageHandle` のメンバ関数実装を提供します。
//----------------------------------------------------------------------------

#include "ImageHandle.h"
#include <utility>    // for std::swap

//----------------------------------------------------------------------------
//! デフォルトコンストラクタ
//! @note 無効なハンドルを示す -1 で初期化する
//----------------------------------------------------------------------------
ImageHandle::ImageHandle() noexcept
    : m_h(-1)
{
}

//----------------------------------------------------------------------------
//! ハンドル指定コンストラクタ
//! @param h DxLib の画像ハンドル
//----------------------------------------------------------------------------
ImageHandle::ImageHandle(int h) noexcept
    : m_h(h)
{
}

//----------------------------------------------------------------------------
//! 画像ファイルからハンドルをロードして ImageHandle を返す
//! @param path 画像ファイルのパス
//! @return 読み込まれたハンドルを保持する ImageHandle
//----------------------------------------------------------------------------
ImageHandle ImageHandle::Load(const std::string& path)
{
    int h = LoadGraph(path.c_str());
    return ImageHandle(h);
}

//----------------------------------------------------------------------------
//! デストラクタ
//! @note 有効なハンドルがあれば解放する
//----------------------------------------------------------------------------
ImageHandle::~ImageHandle()
{
    if(m_h != -1) {
        DeleteGraph(m_h);
        m_h = -1;
    }
}

//----------------------------------------------------------------------------
//! ムーブコンストラクタ
//! @param o 移動元オブジェクト
//----------------------------------------------------------------------------
ImageHandle::ImageHandle(ImageHandle&& o) noexcept
    : m_h(o.m_h)
{
    o.m_h = -1;
}

//----------------------------------------------------------------------------
//! ムーブ代入演算子
//! @param o 移動元オブジェクト
//! @return *this
//----------------------------------------------------------------------------
ImageHandle& ImageHandle::operator=(ImageHandle&& o) noexcept
{
    if(this != &o) {
        if(m_h != -1) {
            DeleteGraph(m_h);
        }
        m_h   = o.m_h;
        o.m_h = -1;
    }
    return *this;
}

//----------------------------------------------------------------------------
//! ハンドルが有効かを返す
//! @return 有効なら true
//----------------------------------------------------------------------------
bool ImageHandle::IsValid() const noexcept
{
    return m_h != -1;
}

//----------------------------------------------------------------------------
//! 内部の生ハンドルを取得する
//! @return DxLib の画像ハンドル
//----------------------------------------------------------------------------
int ImageHandle::Get() const noexcept
{
    return m_h;
}

//----------------------------------------------------------------------------
//! 真偽評価
//! @return ハンドルが有効なら true
//----------------------------------------------------------------------------
ImageHandle::operator bool() const noexcept
{
    return IsValid();
}

//----------------------------------------------------------------------------
//! ハンドルを解放して値を返す
//! @return 解放前のハンドル値
//----------------------------------------------------------------------------
int ImageHandle::Release() noexcept
{
    int t = m_h;
    m_h   = -1;
    return t;
}

//----------------------------------------------------------------------------
//! ハンドルを交換する
//! @param o 交換先オブジェクト
//----------------------------------------------------------------------------
void ImageHandle::swap(ImageHandle& o) noexcept
{
    std::swap(m_h, o.m_h);
}
