//============================================================================
//! @file   ObjectBase.cpp
//! @brief  ゲームオブジェクト共通基底クラスの実装
//! @author レオ
//============================================================================
#include "ObjectBase.h"

namespace Object {
//-----------------------------------------------------------
//! @brief デストラクタ
//! @details コンポーネントの終了処理だけを保証する（End() は多重に呼ばれても安全）。
//!          デストラクタ内では仮想関数が派生クラスへ届かないため、
//!          派生クラスの OnEnd() はここでは呼ばれない。
//-----------------------------------------------------------
ObjectBase::~ObjectBase()
{
    End();
}

//-----------------------------------------------------------
//! @brief オブジェクト名を取得する
//! @return オブジェクト名
//-----------------------------------------------------------
std::string ObjectBase::GetName() const
{
    return m_name;
}

//! @brief オブジェクト名を設定する
void ObjectBase::SetName(const std::string& n)
{
    m_name = n;
}

//-----------------------------------------------------------
//! @brief 初期化処理
//! @details 全コンポーネントを初期化してからオブジェクト固有処理を呼ぶ
//-----------------------------------------------------------
void ObjectBase::Init()
{
    for(auto& comp : m_components) {
        comp->Init();
    }
    OnInit();
}

//-----------------------------------------------------------
//! @brief 更新処理
//! @details 非アクティブ（IsActive() == false）の場合は何もしない。
//!          アクティブな場合、全コンポーネントを更新してから
//!          オブジェクト固有処理を呼ぶ
//-----------------------------------------------------------
void ObjectBase::Update()
{
    if(!m_active) return;

    for(auto& comp : m_components) {
        comp->Update();
    }
    OnUpdate();
}

//-----------------------------------------------------------
//! @brief デバッグ描画処理
//! @details 全コンポーネントをデバッグ描画してからオブジェクト固有処理を呼ぶ
//-----------------------------------------------------------
void ObjectBase::DrawDebug()
{
    for(auto& comp : m_components) {
        comp->DrawDebug();
    }

    OnDrawDebug();
}

//-----------------------------------------------------------
//! @brief 描画処理
//! @details 非表示（IsVisible() == false）の場合は何もしない。
//!          表示対象の場合、全コンポーネントを描画してから
//!          オブジェクト固有処理を呼ぶ
//-----------------------------------------------------------
void ObjectBase::Draw()
{
    if(!m_visible) return;

    for(auto& comp : m_components) {
        comp->Draw();
    }
    OnDraw();
}

//-----------------------------------------------------------
//! @brief 終了処理
//! @details 全コンポーネントを終了してからオブジェクト固有処理を呼ぶ
//-----------------------------------------------------------
void ObjectBase::End()
{
    for(auto& comp : m_components) {
        comp->End();
    }
    m_components.clear();
    OnEnd();
}

}    // namespace Object
